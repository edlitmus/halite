// proseOf joins the chapters a person wrote about the handbook's own topics,
// leaving out the generated ones and the pre-existing guides included in it,
// so that a word in a generated reference cannot satisfy a check meant to
// find it in the teaching text.
func proseOf(t *testing.T, names ...string) string {
	t.Helper()
	root := repoRoot(t)
	var b strings.Builder
	for _, n := range names {
		b.WriteString(readDoc(t, filepath.Join(root, "docs", "handbook", n)))
		b.WriteString("\n")
	}
	return b.String()
}

func allProse(t *testing.T) string {
	t.Helper()
	root := repoRoot(t)
	entries, err := os.ReadDir(filepath.Join(root, "docs", "handbook"))
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		n := e.Name()
		if strings.HasSuffix(n, ".md") && !strings.HasPrefix(n, "gen-") && n != "README.md" {
			names = append(names, n)
		}
	}
	return proseOf(t, names...)
}

// Every command of every binary is named in the handbook, by the words a
// person types.
func TestEveryCommandIsInTheHandbook(t *testing.T) {
	root := repoRoot(t)
	prose := allProse(t)
	found := 0
	for _, binary := range []string{"halite-node", "halite-hub", "halite-api"} {
		for _, sub := range subcommandsOf(t, root, binary) {
			if _, deliberate := undocumented[binary+" "+sub]; deliberate {
				continue
			}
			found++
			if strings.Contains(prose, binary+" "+sub) {
				continue
			}
			t.Errorf("`%s %s` is a command and no handbook chapter writes it out. A command a "+
				"reader cannot find is one they do not know they have; the runbooks and "+
				"chapters teach by example, so give it one.", binary, sub)
		}
	}
	if found == 0 {
		t.Fatal("no commands were read; this audit has stopped checking")
	}
}

// Every beacon this build knows of, built or waiting, is in the chapter on
// beacons, so a reader learns what exists and what does not.
func TestEveryBeaconIsInTheBeaconChapter(t *testing.T) {
	chapter := proseOf(t, "19-beacons.md")
	names := beacon.New().Names()
	for _, n := range names {
		if !strings.Contains(chapter, "`"+n+"`") {
			t.Errorf("the %s beacon is not named in docs/handbook/19-beacons.md; "+
				"say what it does, or that it is not built", n)
		}
	}
	if len(names) == 0 {
		t.Fatal("no beacons were found; this audit has stopped checking")
	}
}

// Every runner is in the chapter on runners, built or not.
func TestEveryRunnerIsInTheRunnerChapter(t *testing.T) {
	chapter := proseOf(t, "22-runners-and-mine.md")
	// The chapter groups a namespace's functions in one cell (`nodegroups.list`,
	// `.show`, `.expand`), so a function is also present when its namespace is
	// named with the function's last word in a following cell. Accept the
	// qualified name, or a leading-dot short form after it.
	names := hub.NewRunners().Names()
	missing := 0
	for _, n := range names {
		if strings.Contains(chapter, n) {
			continue
		}
		ns, fn, _ := strings.Cut(n, ".")
		if strings.Contains(chapter, "`"+ns+".") && strings.Contains(chapter, "`."+fn+"`") {
			continue
		}
		t.Errorf("the runner %s is not in docs/handbook/22-runners-and-mine.md", n)
		missing++
	}
	if len(names) == 0 {
		t.Fatal("no runners were found; this audit has stopped checking")
	}
}

// Every requisite is in the requisites chapter, and the list here is a real
// list of requisites (so a renamed one fails this and not just the book).
func TestEveryRequisiteIsInTheRequisiteChapter(t *testing.T) {
	chapter := proseOf(t, "06-requisites.md")
	for _, n := range []string{"require", "require_any", "watch", "watch_any", "onchanges",
		"onchanges_any", "onfail", "onfail_any", "onfail_all", "prereq", "use", "listen"} {
		if !state.IsRequisiteArg(n) {
			t.Errorf("%s is no longer a requisite; update this list and the chapter", n)
		}
		if !strings.Contains(chapter, "`"+n+"`") {
			t.Errorf("the %s requisite is not in docs/handbook/06-requisites.md", n)
		}
	}
}

// Every event tag the hub says it fires is in the event reference.
func TestEveryEventTagIsInTheEventReference(t *testing.T) {
	tags, err := handbook.EventTags(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	if len(tags) == 0 {
		t.Fatal("`halite-hub event tags` printed no tags; this audit has stopped checking")
	}
	norm := func(s string) string {
		s = regexp.MustCompile(`<[^>]+>`).ReplaceAllString(s, "<>")
		s = strings.ReplaceAll(s, "…", "...")
		return s
	}
	chapter := norm(proseOf(t, "45-event-reference.md"))
	for _, tag := range tags {
		// halite/state/<jid>/<node>/<result> is written in the chapter with
		// its two results; match on the family up to the result.
		probe := norm(tag)
		probe = strings.TrimSuffix(probe, "/<>")
		if strings.HasSuffix(probe, "...") {
			probe = strings.TrimSuffix(probe, "...")
		}
		if !strings.Contains(chapter, probe) {
			t.Errorf("the event tag %s (from `halite-hub event tags`) is not in "+
				"docs/handbook/45-event-reference.md", tag)
		}
	}
}

// The index is made from the build's own registries, and finds the things
// the book is about. A smoke test, because an index that silently indexed
// nothing would look like an index.
func TestTheIndexFindsWhatTheBookIsAbout(t *testing.T) {
	bk := loadBook(t)
	if err := bk.Load(nil, false); err != nil {
		t.Fatal(err)
	}
	known, err := handbook.KnownIdentifiers(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	idx := handbook.BuildIndex(bk, known)
	have := map[string]bool{}
	for _, e := range idx {
		have[e.Kind+"|"+e.Term] = true
	}
	for _, want := range []string{
		handbook.KindCommand + "|halite-hub keys accept",
		handbook.KindCommand + "|halite-node state apply",
		handbook.KindFunction + "|file.managed",
		handbook.KindSetting + "|node_id",
		handbook.KindSetting + "|enrollment_mode",
		handbook.KindRunner + "|manage.status",
		handbook.KindBeacon + "|filechanges",
		handbook.KindRequisite + "|onchanges",
		handbook.KindMetric + "|halite_hub_nodes_connected",
		handbook.KindEvent + "|halite/node/<node>/start",
		handbook.KindPackage + "|internal/state",
		handbook.General + "|idempotency",
	} {
		if !have[want] {
			t.Errorf("the index has no entry %q", want)
		}
	}
	t.Logf("the index has %d entries", len(idx))
}

// The HTML edition builds, and building it twice gives the same bytes: SPEC
// 4.3 asks the release to be reproducible, and the handbook is part of it.
func TestTheHandbookBuildsReproducibly(t *testing.T) {
	root := repoRoot(t)
	build := func() map[string]string {
		bk, err := handbook.ReadContents(root)
		if err != nil {
			t.Fatal(err)
		}
		known, err := handbook.KnownIdentifiers(root)
		if err != nil {
			t.Fatal(err)
		}
		out := t.TempDir()
		names, err := handbook.Build(bk, handbook.SiteOptions{Out: out, Version: "0.0.0-test", Known: known,
			RepoURL: "https://example.invalid/blob/main/"})
		if err != nil {
			t.Fatal(err)
		}
		files := map[string]string{}
		for _, n := range names {
			b, err := os.ReadFile(filepath.Join(out, n))
			if err != nil {
				t.Fatal(err)
			}
			files[n] = string(b)
		}
		return files
	}
	a, b := build(), build()
	if len(a) < 10 {
		t.Fatalf("the build wrote %d files", len(a))
	}
	for _, must := range []string{"index.html", "genindex.html", "handbook.html", "handbook.css"} {
		if _, ok := a[must]; !ok {
			t.Errorf("the build did not write %s", must)
		}
	}
	for name, body := range a {
		if b[name] != body {
			t.Errorf("%s differs between two builds of the same tree; the handbook must be reproducible", name)
		}
	}
}
