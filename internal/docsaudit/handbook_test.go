// The handbook is documentation that ships in every release, so it is held
// to the code the way the generated references are. These tests are why
// "it is part of any release so it is always kept up to date" is a property
// of the build and not an intention: a feature added without a word about it
// in the book fails here, and so does a book that has drifted from the code.
//
// Two kinds of check. The structure of the book (links, headings, runbook
// sections, the examples it quotes) is internal/handbook's Check. What is
// here is the comparison with the rest of the repository: that the generated
// chapters are current, that every package is described, and that the things
// the build ships are named in the prose that is supposed to teach them.

func loadBook(t *testing.T) *handbook.Book {
	t.Helper()
	bk, err := handbook.ReadContents(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	return bk
}

func TestTheHandbookIsWellFormed(t *testing.T) {
	bk := loadBook(t)
	problems := handbook.Check(bk)
	for _, p := range problems {
		t.Error(p)
	}
	if len(problems) == 0 {
		t.Logf("checked %d chapters", len(bk.All))
	}
}

// Every generated chapter matches what the generator produces now, and the
// contents page matches the book.
func TestTheHandbooksGeneratedChaptersAreCurrent(t *testing.T) {
	root := repoRoot(t)
	files, err := handbook.Generate(root)
	if err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		// The CLI reference is the programs' own `help`, and help prints the
		// platform's default paths (/etc/halite on Linux, /usr/local/etc/halite
		// on FreeBSD, C:\ProgramData\Halite on Windows). The committed page is
		// the Linux one, so it is compared only where it can be reproduced;
		// the Linux legs of CI hold it for the rest. Found when the first CI
		// run failed on FreeBSD and Windows with a one-line path difference.
		if name == "docs/handbook/gen-cli.md" && runtime.GOOS != "linux" {
			continue
		}
		got, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			t.Errorf("%s: %v\nrun: go run ./tools/handbook gen", name, err)
			continue
		}
		if string(got) != files[name] {
			t.Errorf("%s is out of date with the code.\nRun `go run ./tools/handbook gen` and commit the result.\n\n%s",
				name, firstDifference(string(got), files[name]))
		}
		head := string(got)
		if len(head) > 400 {
			head = head[:400]
		}
		if !strings.Contains(head, "Generated by tools/") {
			t.Errorf("%s does not say it is generated near the top", name)
		}
	}

	bk := loadBook(t)
	if err := bk.Load(nil, false); err != nil {
		t.Fatal(err)
	}
	readme, err := os.ReadFile(filepath.Join(root, "docs", "handbook", "README.md"))
	if err != nil {
		t.Fatalf("docs/handbook/README.md: %v\nrun: go run ./tools/handbook gen", err)
	}
	if want := handbook.Contents(bk); string(readme) != want {
		t.Errorf("docs/handbook/README.md is out of date with the book's contents.\n"+
			"Run `go run ./tools/handbook gen` and commit the result.\n\n%s",
			firstDifference(string(readme), want))
	}
}

